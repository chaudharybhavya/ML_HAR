"""Build docs/data.js (data for the website's tuning, selection, test and error sections) from saved results.

Run from the repository root:  python docs/make_data.py
Inputs (all written by the notebooks):
  results/cv_logistic.csv, results/cv_svm.csv, results/cv_forest.csv   (Parts 4-6: every fold score of every setting)
  results/test_predictions_lasso.csv                                   (Part 7: final model on the 9 test people)
  results/extra_experiments.csv                                        (Part 3, Cell 6: leakage splits, physics baseline)
Nothing here is fitted or tuned; it only summarises the saved results.
"""
import json
import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score

# ---- cross-validation results: one entry per setting, in the order the notebooks saved them ----
cv = pd.concat([pd.read_csv(f"results/cv_{m}.csv") for m in ["logistic", "svm", "forest"]], ignore_index=True)
models = {}
for model, rows in cv.groupby("model", sort=False):
    models[model] = []
    for setting, r in rows.groupby("setting", sort=False):
        f = r.sort_values("fold")["macro_f1"].to_numpy()
        models[model].append({"setting": setting,
                              "mean": round(float(f.mean()), 4),
                              "se": round(float(f.std(ddof=1) / np.sqrt(len(f))), 4),   # SE = sample std / sqrt(7)
                              "folds": [round(float(v), 4) for v in f]})

# ---- final test: lasso, C = 0.1, on the 9 test people ----
t = pd.read_csv("results/test_predictions_lasso.csv")
probs = t[["p_walk", "p_up", "p_down", "p_sit", "p_stand", "p_lie"]]
people = sorted(t["person"].unique())
test = {
    "macro_f1": round(f1_score(t["true"], t["pred"], average="macro"), 4),
    "accuracy": round(accuracy_score(t["true"], t["pred"]), 4),
    "per_person": {str(p): round(f1_score(g["true"], g["pred"], average="macro"), 4)
                   for p, g in t.groupby("person")},
    "n_person": {str(p): int((t["person"] == p).sum()) for p in people},
    "cm_by_person": {str(p): confusion_matrix(g["true"], g["pred"], labels=[1, 2, 3, 4, 5, 6]).tolist()
                     for p, g in t.groupby("person")},
    # 4 decimals, so no window moves across the 0.6 / 0.9 confidence bands used on the page
    "conf": [round(float(c), 4) for c in probs.max(axis=1)],
    "wrong": [int(w) for w in (t["true"] != t["pred"])],
}

# ---- Part 3, Cell 6: the three-way leakage experiment and the physics baseline ----
ex = pd.read_csv("results/extra_experiments.csv")
extra = {}
for name, r in ex.groupby("experiment", sort=False):
    r = r.sort_values("fold")
    extra[name] = {"macro_f1": round(float(r["macro_f1"].mean()), 4),
                   "f1_std": round(float(r["macro_f1"].std(ddof=1)), 4),          # sample std over the 7 folds
                   "accuracy": round(float(r["accuracy"].mean()), 4),
                   "folds": [round(float(v), 4) for v in r["macro_f1"]]}

with open("docs/data.js", "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by docs/make_data.py from results/cv_*.csv, results/test_predictions_lasso.csv "
             "and results/extra_experiments.csv.\n")
    fh.write("window.HAR = " + json.dumps({"models": models, "test": test, "extra": extra},
                                          separators=(",", ":")) + ";\n")
print("settings:", {m: len(v) for m, v in models.items()}, "| test windows:", len(t),
      "| extra experiments:", list(extra))
