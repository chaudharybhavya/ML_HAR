"""Build docs/phone.js (data for the website's phone section) from saved results.

Run from the repository root:  python docs/make_phone_data.py
Inputs: results/phone_predictions_bhavya.csv, results/phone_features_bhavya.csv (Part 10 / Part 9),
and the raw training signals in data/raw/UCI HAR Dataset/train/ (training people only) for the
sitting/standing gravity clouds. Nothing here is fitted or tuned.
"""
import json
import os
import sys
import numpy as np
import pandas as pd

sys.path.insert(0, os.getcwd())   # config.py lives in the repository root
from config import DATA

pred = pd.read_csv("results/phone_predictions_bhavya.csv")
feat = pd.read_csv("results/phone_features_bhavya.csv", usecols=["activity", "window", "gravity_x", "gravity_y", "gravity_z"])
phone = pred.merge(feat, on=["activity", "window"], validate="one_to_one")

windows = [[int(r.label), int(r.pred), round(r.confidence, 3), round(r.gravity_y, 3), round(r.gravity_z, 3), round(r.start_s, 2)]
           for r in phone.itertuples()]

# UCI training people: mean gravity (total acceleration) per window, sitting and standing only
y = np.loadtxt(DATA + "/train/y_train.txt", dtype=int)
mean = {a: np.loadtxt(f"{DATA}/train/Inertial Signals/total_acc_{a}_train.txt").mean(axis=1) for a in "yz"}
clouds = {name: [[round(mean["y"][i], 3), round(mean["z"][i], 3)] for i in np.where(y == code)[0]]
          for name, code in [("sit", 4), ("stand", 5)]}

data = {"columns": ["true", "pred", "confidence", "gravity_y", "gravity_z", "start_s"],
        "windows": windows, "uci_train_still": clouds}
with open("docs/phone.js", "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by docs/make_phone_data.py from results/phone_*_bhavya.csv and the UCI training signals.\n")
    fh.write("window.PHONE = " + json.dumps(data, separators=(",", ":")) + ";\n")
print("phone windows:", len(windows), "| UCI sit/stand points:", len(clouds["sit"]), len(clouds["stand"]))
